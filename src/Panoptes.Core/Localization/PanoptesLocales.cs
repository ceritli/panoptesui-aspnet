        public static void Register(PanoptesLocaleInfo locale)
        {
            if (locale == null || string.IsNullOrWhiteSpace(locale.Code)) return;
            _locales[locale.Code] = locale;
            if (!string.IsNullOrWhiteSpace(locale.Culture))
            {
                _locales[locale.Culture] = locale;
            }
        }

        public static PanoptesLocaleInfo Get(string? codeOrCulture)
        {
            if (!string.IsNullOrWhiteSpace(codeOrCulture) && _locales.TryGetValue(codeOrCulture, out var loc))
            {
                return loc;
            }

            // Deny hyphen or country code fallback (e.g. "en-GB" -> "en")
            if (!string.IsNullOrWhiteSpace(codeOrCulture) && codeOrCulture.Contains('-'))
            {
                var twoLetter = codeOrCulture.Split('-')[0];
                if (_locales.TryGetValue(twoLetter, out var twoLetterLoc))
                {
                    return twoLetterLoc;
                }
            }

            return _locales["tr"]; // Default Turkish
        }

        public static IReadOnlyCollection<PanoptesLocaleInfo> All
        {
            get
            {
                // Unique by Code
                return _locales.Values.GroupBy(x => x.Code).Select(g => g.First()).ToList();
            }
        }

        public static string[] SupportedCultures =>
            All.Select(x => x.Culture).Distinct().ToArray();
    }
